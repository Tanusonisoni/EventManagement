async function generateTicket(ticket) {
    const doc = new jsPDF({
        orientation: "landscape",
        unit: "mm",
        format: [120, 210],
    });

    // =========================
    // COLORS
    // =========================
    const yellow = [255, 205, 55];
    const dark = [35, 35, 35];
    const gray = [90, 90, 90];

    // =========================
    // PAGE BACKGROUND
    // =========================
    doc.setFillColor(255, 255, 255);
    doc.rect(0, 0, 210, 120, "F");

    // =========================
    // OUTER TICKET BORDER
    // =========================
    doc.setFillColor(255, 250, 225);
    doc.setDrawColor(...yellow);
    doc.setLineWidth(1);

    doc.roundedRect(
        8,      // x
        8,      // y
        194,    // width
        104,    // height
        2,
        2,
        "FD"
    );

    // =========================
    // INNER BORDER
    // =========================
    doc.setDrawColor(180, 150, 50);
    doc.setLineWidth(0.4);

    doc.roundedRect(
        10,
        10,
        190,
        100,
        1,
        1
    );

    // =========================
    // TOP HEADER
    // =========================
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...gray);

    doc.text(
        formatDate(ticket.date),
        105,
        22,
        { align: "center" }
    );

    // =========================
    // EVENT NAME
    // =========================
    doc.setFont("helvetica", "bold");
    doc.setFontSize(20);
    doc.setTextColor(...dark);

    doc.text(
        String(ticket.eventName || "EVENT"),
        105,
        32,
        { align: "center" }
    );

    // =========================
    // TICKET TYPE
    // =========================
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(...gray);

    doc.text(
        "EVENT ENTRY PASS",
        105,
        39,
        { align: "center" }
    );

    // =========================
    // ATTENDEE
    // =========================
    doc.setFont("helvetica", "italic");
    doc.setFontSize(14);
    doc.setTextColor(...dark);

    doc.text(
        String(ticket.name || "Guest"),
        105,
        48,
        { align: "center" }
    );

    // =========================
    // DASHED DIVIDER
    // =========================
    doc.setDrawColor(120, 120, 120);
    doc.setLineWidth(0.3);

    // Dashed line
    for (let x = 10; x < 200; x += 5) {
        doc.line(x, 55, x + 2.5, 55);
    }

    // =========================
    // LEFT SIDE - EVENT INFO
    // =========================
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...dark);

    doc.text(
        `Email: ${String(ticket.email || "N/A")}`,
        18,
        65
    );

    doc.text(
        `Category: ${String(ticket.category || "N/A")}`,
        18,
        72
    );

    doc.text(
        `Ticket ID: ${String(ticket.ticketId || "N/A")}`,
        18,
        79
    );

    // =========================
    // CENTER - DATE / TIME / VENUE
    // =========================
    doc.text(
        `Date: ${formatDate(ticket.date)}`,
        90,
        65
    );

    doc.text(
        `Time: ${String(ticket.time || "N/A")}`,
        90,
        72
    );

    doc.text(
        `Venue: ${String(ticket.venue || "N/A")}`,
        90,
        79
    );

    // =========================
    // PAYMENT
    // =========================
    doc.text(
        `Amount: Rs. ${String(ticket.amount || 0)}`,
        18,
        88
    );

    doc.text(
        `Status: ${String(ticket.paymentStatus || "Paid")}`,
        90,
        88
    );

    // =========================
    // QR CODE
    // =========================
    const qrString = JSON.stringify({
        ticketId: String(ticket.ticketId),
        bookingId: String(ticket.bookingId),
    });

    const downloadUrl =
    `http://localhost:5000/${ticket.bookingId}/download-ticket`;

    const qr = await toDataURL(qrString);

    doc.addImage(
        qr,
        "PNG",
        165,
        61,
        28,
        28
    );

    doc.setFontSize(6);
    doc.setFontSize(6);
    doc.setTextColor(...gray);

    doc.text(
        "Scan for Verification",
        179,
        94,
        { align: "center" }
    );

    // =========================
    // FOOTER
    // =========================
    doc.setFont("helvetica", "normal");
    doc.setFontSize(6);
    doc.setTextColor(100, 100, 100);

    doc.text(
        "Generated by MindVerse Event Management System",
        105,
        103,
        { align: "center" }
    );

    return Buffer.from(
        doc.output("arraybuffer")
    );
}


// =========================
// DATE FORMATTER
// =========================
function formatDate(date) {
    if (!date) {
        return "N/A";
    }

    const d = new Date(date);

    if (isNaN(d.getTime())) {
        return String(date);
    }

    return d.toLocaleDateString("en-US", {
        month: "long",
        day: "numeric",
        year: "numeric",
    }).toUpperCase();
}

export default generateTicket;